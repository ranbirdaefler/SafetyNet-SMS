"""v2 augmentation cards (Florian, Sat 3 Oct, after the v1 encoder failed CG1/CG5). Built from protocol word lists only
(the T-list, the negation cues and the fixed option texts); never from a test set, Y-dev or the CG probe strings.
Messages are generated by GPT (gpt-5.5, the X generator). Labels come from the card.

Three kinds:
- terse: a very short message using one T-list term (or a duration with a symptom word) for one sign;
- denial: the parent denies several caregiver signs (often a long all-negative list) and mentions a mild complaint;
- mixed: one sign present among denials of others.
"""
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from app import lexicon  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cards import HEADS, MILD, _age, _lang  # noqa: E402

DURATION = {"cough_long": ("cough", "kikohozi", 14, 30), "diarrhoea_long": ("diarrhoea", "kuhara", 14, 30),
            "fever_long": ("fever", "homa", 7, 14)}
DENY = {
    "convulsions": "no fits / convulsions (deny it, e.g. 'no fits', 'hana degedege')",
    "not_drink_feed": "drinks and breastfeeds well (say it positively or as 'no problem drinking')",
    "vomits_everything": "not vomiting everything (e.g. 'not vomiting', 'hatapiki')",
    "sleepy_unconscious": "awake and alert, not unusually sleepy (e.g. 'he wakes up fine', 'anaamka')",
    "blood_stool": "no blood in the stool (e.g. 'no blood in stool', 'hakuna damu kwenye kinyesi')",
    "cough_long": "cough only for a few days (2 to 5 days)",
    "diarrhoea_long": "loose stool only for 1 to 3 days",
    "fever_long": "fever only for 1 to 3 days",
}


def terse_cards(rng):
    cards = []
    for sign, terms in lexicon.T_LIST.items():
        for t in terms:
            for _ in range(4):
                age = rng.random() < 0.6
                m, txt = _age(rng)
                cards.append({"kind": "terse", "signs": [sign], "term": t, "age_months": m if age else None,
                              "age_text": txt if age else "no age", "lang": _lang(rng)})
    for sign, (en, sw, lo, hi) in DURATION.items():
        for _ in range(10):
            age = rng.random() < 0.6
            m, txt = _age(rng)
            d = rng.randint(lo, hi)
            cards.append({"kind": "terse", "signs": [sign], "term": f"{rng.choice([en, sw])} for {d} days",
                          "age_months": m if age else None, "age_text": txt if age else "no age", "lang": _lang(rng)})
    return cards


def denial_cards(rng, n):
    cards = []
    for _ in range(n):
        k = rng.choice([2, 3, 4, 5, 6, 8])
        denied = rng.sample(HEADS, k)
        m, txt = _age(rng)
        cards.append({"kind": "denial", "signs": [], "denied": denied, "age_months": m, "age_text": txt,
                      "mild": rng.choice(MILD), "lang": _lang(rng)})
    return cards


def mixed_cards(rng, n):
    cards = []
    for i in range(n):
        sign = HEADS[i % len(HEADS)]
        others = [h for h in HEADS if h != sign]
        denied = rng.sample(others, rng.choice([2, 3, 4, 5]))
        m, txt = _age(rng)
        if sign in DURATION:
            en, sw, lo, hi = DURATION[sign]
            term = f"{rng.choice([en, sw])} for {rng.randint(lo, hi)} days"
        else:
            term = rng.choice(lexicon.T_LIST[sign])
        cards.append({"kind": "mixed", "signs": [sign], "term": term, "denied": denied, "age_months": m,
                      "age_text": txt, "lang": _lang(rng)})
    return cards


def all_cards(seed=5005):
    rng = random.Random(seed)
    cards = terse_cards(rng) + denial_cards(rng, 160) + mixed_cards(rng, 160)
    rng.shuffle(cards)
    for i, c in enumerate(cards):
        c["id"] = f"x_aug-{i + 1:04d}"
        c["category"] = "danger" if c["signs"] else "no_danger"
        c["present"] = [int(h in c["signs"]) for h in HEADS]
        c["style"] = []
    return cards


def render(card):
    lines = ["Case card:", f"- Language: {card['lang']}"]
    lines.append("- Age: no age (do not state the child's age)" if card["age_text"] == "no age"
                 else f"- Age: the child is {card['age_text']}")
    if card["kind"] == "terse":
        lines.append(f"- A very short SMS (under 60 characters) that reports this danger sign using exactly the words "
                     f"'{card['term']}' (you may translate the duration words into the card's language)")
        lines.append("- Nothing else: no other symptom, no greeting needed")
    elif card["kind"] == "denial":
        lines.append(f"- The child has {card['mild']}")
        for h in card["denied"]:
            lines.append(f"- The parent says: {DENY[h]}")
        lines.append("- Write the denials as a list or a run of short phrases, the way a parent answers a checklist")
    else:
        lines.append(f"- The child has this danger sign, said with the words '{card['term']}'")
        for h in card["denied"]:
            lines.append(f"- The parent also says: {DENY[h]}")
    lines.append("- Number of SMS: one")
    lines.append("Write the SMS now. Output only the JSON.")
    return "\n".join(lines)
